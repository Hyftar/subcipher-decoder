defmodule Subcipher.CipherFixtures do
  @moduledoc """
  Fixtures built from `test/fixtures/pangram_*` (generated by
  `scripts/make_fixtures.sh`; the `.glyphs.json` files are produced by the
  JS detector tests: `node --test assets/test/*.test.mjs`).
  """

  alias Subcipher.Ciphers
  alias Subcipher.Ciphers.Analysis

  @dir Path.expand("../fixtures", __DIR__)

  def fixture_path(name), do: Path.join(@dir, name)

  @doc "Plain-text letters of the pangram, in reading order, without spaces."
  def pangram_letters do
    fixture_path("pangram.txt")
    |> File.read!()
    |> String.replace(~r/\s/, "")
    |> String.graphemes()
  end

  def pangram_text, do: File.read!(fixture_path("pangram.txt"))

  @doc "The JSON payload the browser sends after detection."
  def detection_payload(name \\ "pangram_clean") do
    fixture_path("#{name}.glyphs.json") |> File.read!() |> Jason.decode!()
  end

  def detected_glyphs(name \\ "pangram_clean") do
    {:ok, glyphs} = Analysis.parse_detection(detection_payload(name))
    glyphs
  end

  @doc "An uploaded picture, as passed to `Ciphers.create_puzzle/4` and `Ciphers.add_image/3`."
  def image_upload(name) do
    payload = detection_payload(name)

    %{
      path: fixture_path("#{name}.png"),
      ext: ".png",
      width: payload["width"],
      height: payload["height"]
    }
  end

  def puzzle_fixture(name \\ "pangram_clean", attrs \\ %{}) do
    {:ok, puzzle} =
      Ciphers.create_puzzle(
        Map.merge(%{title: "Pangram"}, attrs),
        image_upload(name),
        detected_glyphs(name)
      )

    puzzle
  end

  @doc "Adds another picture to `puzzle`; returns the reloaded puzzle."
  def add_image_fixture(puzzle, name) do
    {:ok, puzzle, _stats} = Ciphers.add_image(puzzle, image_upload(name), detected_glyphs(name))
    puzzle
  end

  @doc """
  Maps each symbol id to the plain letter its glyphs stand for (pangram
  pictures; the first picture of the puzzle is used).
  """
  def solution(puzzle) do
    first = hd(puzzle.images).id

    puzzle.glyphs
    |> Enum.filter(&(&1.image_id == first))
    |> Enum.zip(pangram_letters())
    |> Map.new(fn {g, letter} -> {g.symbol_id, letter} end)
  end
end
